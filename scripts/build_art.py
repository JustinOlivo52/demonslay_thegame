#!/usr/bin/env python3
"""Cut the source illustrations in art/source/ into game sprites.

Writes trimmed, downscaled PNGs to public/art/ and the rig measurements to
src/rig.ts. Run from the repository root after replacing a source image:

    python3 scripts/build_art.py

Requires Pillow (pip install pillow). The outputs are committed, so the game
itself never needs Python.
"""
import json
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / 'art' / 'source', ROOT / 'public' / 'art'

# Characters are stored at 16% of the source size, the katana at 8%: enough
# detail for the zoomed camera without oversized textures.
CHAR_TEX, KATANA_TEX = 0.16, 0.08

# Measurements in source-image pixels, read off the illustrations.
SLAYER = {
    'world_height': 105, 'top': 2, 'feet': (540, 1436),
    'leg_top': 880,        # leg pieces start here; the body overlaps them down to body_cut
    'body_cut': 930,
    'leg_split': 570,      # x where the two legs separate
    'scabbard': (770, 960),  # region right of x / above y stays on the body
    'hip_l': (450, 905), 'hip_r': (670, 905),
    'hand': (832, 782),
}
DEMON = {'world_height': 120, 'top': 0, 'feet': (560, 1445), 'eyes': [(703, 131), (737, 143)]}
KATANA = {'grip': (420, 348), 'tip': (2152, 300), 'world_length': 62}


def save(img, name, factor):
    w, h = max(1, round(img.width * factor)), max(1, round(img.height * factor))
    img.resize((w, h), Image.LANCZOS).save(OUT / f'{name}.png', optimize=True)
    return w, h


def trimmed(img):
    box = img.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
    return img.crop(box), box


def masked(img, keep):
    out = img.copy()
    px, w, h = out.load(), out.width, out.height
    for y in range(h):
        for x in range(w):
            if not keep(x, y):
                px[x, y] = (0, 0, 0, 0)
    return out


def piece(img, name, keep, anchor, feet, scale):
    """Cut a masked piece; return where its anchor sits relative to the feet (world units)."""
    part, box = trimmed(masked(img, keep))
    tw, th = save(part, name, CHAR_TEX)
    return {
        'key': name, 'width': tw, 'height': th,
        'origin': [round((anchor[0] - box[0]) / part.width, 4), round((anchor[1] - box[1]) / part.height, 4)],
        'x': round((anchor[0] - feet[0]) * scale, 2), 'y': round((anchor[1] - feet[1]) * scale, 2),
    }


def build_slayer():
    img = Image.open(SRC / 'slayer.png').convert('RGBA')
    s, (fx, fy) = SLAYER, SLAYER['feet']
    scale = s['world_height'] / (fy - s['top'])
    split, (scab_x, scab_y), top, cut = s['leg_split'], s['scabbard'], s['leg_top'], s['body_cut']
    scabbard = lambda x, y: x >= scab_x and y < scab_y
    left = lambda x, y: y >= top and x < split
    right = lambda x, y: y >= top and x >= split and not scabbard(x, y)
    body = lambda x, y: y < cut or scabbard(x, y)
    rig = {
        'scale': round(scale / CHAR_TEX, 5),
        'body': piece(img, 'slayer-body', body, (fx, fy), (fx, fy), scale),
        'legL': piece(img, 'slayer-leg-l', left, s['hip_l'], (fx, fy), scale),
        'legR': piece(img, 'slayer-leg-r', right, s['hip_r'], (fx, fy), scale),
        'full': piece(img, 'slayer-full', lambda x, y: True, (fx, fy), (fx, fy), scale),
        'hand': [round((s['hand'][0] - fx) * scale, 2), round((s['hand'][1] - fy) * scale, 2)],
        'height': s['world_height'],
    }
    return rig


def build_demon():
    img = Image.open(SRC / 'demon.png').convert('RGBA')
    d, (fx, fy) = DEMON, DEMON['feet']
    scale = d['world_height'] / (fy - d['top'])
    return {
        'scale': round(scale / CHAR_TEX, 5),
        'full': piece(img, 'demon', lambda x, y: True, (fx, fy), (fx, fy), scale),
        'eyes': [[round((x - fx) * scale, 2), round((y - fy) * scale, 2)] for x, y in d['eyes']],
        'height': d['world_height'],
    }


def build_katana():
    img = Image.open(SRC / 'katana.png').convert('RGBA')
    part, box = trimmed(img)
    tw, th = save(part, 'katana', KATANA_TEX)
    (gx, gy), (tx, ty) = KATANA['grip'], KATANA['tip']
    length = math.hypot(tx - gx, ty - gy)
    return {
        'key': 'katana', 'width': tw, 'height': th,
        'origin': [round((gx - box[0]) / part.width, 4), round((gy - box[1]) / part.height, 4)],
        'scale': round(KATANA['world_length'] / length / KATANA_TEX, 5),
        'angle': round(math.atan2(ty - gy, tx - gx), 4),   # blade axis relative to the image's x axis
        'length': KATANA['world_length'],
    }


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rig = {'slayer': build_slayer(), 'demon': build_demon(), 'katana': build_katana()}
    body = json.dumps(rig, indent=2)
    (ROOT / 'src' / 'rig.ts').write_text(
        '// Generated by scripts/build_art.py from art/source/. Do not edit by hand.\n'
        f'export const RIG = {body} as const;\n'
    )
    print(body)


if __name__ == '__main__':
    main()
